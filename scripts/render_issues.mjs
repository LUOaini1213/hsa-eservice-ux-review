export function load() {
  const issues = parseCsv(read("data/issues.csv"));
  const evidence = parseCsv(read("data/evidence.csv"));
  const sources = Object.fromEntries(parseCsv(read("evidence/sources.csv")).map((s) => [s.id, s]));
  return { issues, evidence, sources };
}

const split = (s) => (s ? s.split(";").filter(Boolean) : []);
const esc = (s) => String(s).replace(/\|/g, "\\|");

export function render({ issues, evidence, sources }) {
  const problems = issues.filter((i) => Number(i.severity) > 0);
  const bySev = [4, 3, 2, 1].map((s) => `${problems.filter((i) => Number(i.severity) === s).length} at severity ${s}`);
  const lines = [];
  lines.push("<!-- Generated by scripts/render_issues.mjs from data/issues.csv and data/evidence.csv. Do not edit by hand. -->");
  lines.push("# Issue log");
  lines.push("");
  lines.push(`${problems.length} issues (${bySev.join(", ")}) and ${issues.length - problems.length} strengths. Severity uses Nielsen's 0 to 4 scale, judged on frequency, impact and persistence. Evidence rows were checked against page snapshots (see evidence/verification.txt).`);
  lines.push("");
  lines.push("| ID | Sev | Issue | Heuristics | DSS controls | Sources |");
  lines.push("|---|:-:|---|---|---|---|");
  const order = [...issues].sort((a, b) => Number(b.severity) - Number(a.severity) || a.id.localeCompare(b.id));
  for (const i of order) {
    const srcs = [...new Set(evidence.filter((e) => e.issue_id === i.id && e.source_id).map((e) => e.source_id))];
    lines.push(`| [${i.id}](#${i.id.toLowerCase()}) | ${i.severity} | ${esc(i.title)} | ${split(i.heuristics).join(", ") || "-"} | ${split(i.dss).join(", ") || "-"} | ${srcs.join(", ") || "-"} |`);
  }
  lines.push("");
  lines.push("Severity scale: " + Object.entries(SEVERITY).map(([k, v]) => `${k} = ${v}`).join("; ") + ".");
  lines.push("");
  lines.push("Heuristics: " + Object.entries(HEURISTICS).map(([k, v]) => `${k} ${v}`).join("; ") + ".");
  lines.push("");
  lines.push("DSS controls: " + Object.entries(DSS).map(([k, v]) => `${k} ${v}`).join("; ") + ".");
  for (const i of order) {
    lines.push("");
    lines.push(`## ${i.id}`);
    lines.push("");
    lines.push(`**${i.title}** (severity ${i.severity}${i.frequency ? `; frequency ${i.frequency}, impact ${i.impact}, persistence ${i.persistence}` : ""})`);
    lines.push("");
    lines.push(i.finding);
    lines.push("");
    lines.push("Evidence:");
    lines.push("");
    for (const e of evidence.filter((x) => x.issue_id === i.id)) {
      const s = sources[e.source_id];
      const where = s ? `[${e.source_id}](${s.url}) ${s.title}` : "computed";
      if (e.type === "quote" || e.type === "html") lines.push(`- ${where}: "${e.evidence}"`);
      else if (e.type === "link") lines.push(`- ${where}: link "${e.evidence}"${e.target ? ` points to \`${e.target}\`` : ""}`);
      else lines.push(`- ${where}: ${e.evidence} (\`${e.target}\`)`);
    }
    lines.push("");
    lines.push(`Recommendation: ${i.recommendation}`);
  }
  return lines.join("\n") + "\n";
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const md = render(load());
  const out = join(root, "review", "02-issue-log.md");
  if (process.argv.includes("--check")) {
    if (read("review/02-issue-log.md") !== md) { console.error("review/02-issue-log.md is stale. Run node scripts/render_issues.mjs"); process.exit(1); }
    console.log("Issue log is up to date.");
  } else {
    writeFileSync(out, md);
    console.log(`Wrote ${out}`);
  }
}
